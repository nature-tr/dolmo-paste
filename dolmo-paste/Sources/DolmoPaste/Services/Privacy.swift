import AppKit

/// 剪贴板隐私约定。
/// 这不是 Apple 的 API，是社区约定：密码管理器往剪贴板写秘密时会打上 ConcealedType 标记。
/// 不遵守它，剪贴板管理器就是一次密码泄露。
enum Privacy {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func shouldStore(_ pasteboard: NSPasteboard, excludedBundleIDs: Set<String>, currentBundleID: String?) -> Bool {
        guard let types = pasteboard.types else { return false }

        if types.contains(concealed) { return false }
        if types.contains(transient) { return false }
        if types.contains(autoGenerated) { return false }

        if let bundleID = currentBundleID, excludedBundleIDs.contains(bundleID) { return false }
        return true
    }

    /// 常用的默认排除名单，用户可在设置里增删
    static let defaultExcludedApps: [String: String] = [
        "com.agilebits.onepassword7": "1Password 7",
        "com.1password.1password": "1Password",
        "com.bitwarden.desktop": "Bitwarden",
        "org.keepassxc.keepassxc": "KeePassXC",
        "com.apple.Passwords": "密码",
    ]
}
